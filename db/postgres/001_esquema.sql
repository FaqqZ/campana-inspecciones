-- Campaña de Inspecciones: esquema PostgreSQL (14 o superior).
-- Equivale al modelo actual de MongoDB. Se aplica sobre una base vacía:
--   psql "$DATABASE_URL" -f db/postgres/001_esquema.sql
-- Convenciones: tablas y columnas en español y snake_case; claves primarias enteras (identity);
-- fechas de negocio (infracción, notificación, vencimientos) como DATE, marcas de tiempo como TIMESTAMPTZ;
-- textos "enumerados" como TEXT con CHECK, para poder ampliarlos sin migrar tipos.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm; -- búsqueda por texto parcial (direcciones, infractores)

-- Mantiene actualizado_en en cada UPDATE.
CREATE OR REPLACE FUNCTION tocar_actualizado_en() RETURNS trigger AS $$
BEGIN
  NEW.actualizado_en = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- Usuarios y campaña
-- ---------------------------------------------------------------------------
CREATE TABLE usuarios (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres        TEXT        NOT NULL,
  apellidos      TEXT        NOT NULL,
  username       TEXT        NOT NULL CHECK (username = lower(username)),
  password_hash  TEXT        NOT NULL, -- bcrypt
  rol            TEXT        NOT NULL CHECK (rol IN ('Administrador', 'Tecnico', 'Juridico', 'Direccion', 'MesaDeEntradas', 'Consulta')),
  activo         BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT usuarios_username_uk UNIQUE (username)
);

CREATE TABLE campanas (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         TEXT        NOT NULL,
  descripcion    TEXT        NOT NULL DEFAULT '',
  fecha_inicio   DATE,
  fecha_fin      DATE,
  activa         BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Catálogos (nombre_norm = nombre sin tildes ni mayúsculas, para no duplicar)
-- ---------------------------------------------------------------------------
CREATE TABLE inspectores (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         TEXT        NOT NULL,
  nombre_norm    TEXT        NOT NULL UNIQUE,
  legajo         TEXT        NOT NULL DEFAULT '',
  activo         BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE motivos_infraccion (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         TEXT        NOT NULL,
  nombre_norm    TEXT        NOT NULL UNIQUE,
  descripcion    TEXT        NOT NULL DEFAULT '', -- normativa que lo respalda
  activo         BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE estados (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre               TEXT        NOT NULL,
  nombre_norm          TEXT        NOT NULL UNIQUE,
  descripcion          TEXT        NOT NULL DEFAULT '',
  es_inicial           BOOLEAN     NOT NULL DEFAULT FALSE, -- estado con el que nace una infracción
  requiere_comentario  BOOLEAN     NOT NULL DEFAULT FALSE, -- el pase a este estado exige comentario
  es_final             BOOLEAN     NOT NULL DEFAULT FALSE, -- estado con el que se cierra al generar el expediente
  orden                INTEGER     NOT NULL DEFAULT 0,
  activo               BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en       TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- A lo sumo un estado inicial y uno final activos.
CREATE UNIQUE INDEX estados_un_inicial ON estados (es_inicial) WHERE es_inicial AND activo;
CREATE UNIQUE INDEX estados_un_final   ON estados (es_final)   WHERE es_final   AND activo;

CREATE TABLE oficinas (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         TEXT        NOT NULL,
  nombre_norm    TEXT        NOT NULL UNIQUE,
  descripcion    TEXT        NOT NULL DEFAULT '',
  es_inicial     BOOLEAN     NOT NULL DEFAULT FALSE, -- oficina donde nace una infracción
  orden          INTEGER     NOT NULL DEFAULT 0,
  activo         BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX oficinas_una_inicial ON oficinas (es_inicial) WHERE es_inicial AND activo;

CREATE TABLE tipos_documento (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre            TEXT        NOT NULL,
  nombre_norm       TEXT        NOT NULL UNIQUE,
  requerido         BOOLEAN     NOT NULL DEFAULT TRUE,
  tiene_vencimiento BOOLEAN     NOT NULL DEFAULT FALSE,
  motivo_asociado_id BIGINT     REFERENCES motivos_infraccion (id) ON DELETE SET NULL, -- infracción potencial si falta o vence
  orden             INTEGER     NOT NULL DEFAULT 0,
  activo            BOOLEAN     NOT NULL DEFAULT TRUE,
  creado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Edificios y su documentación
-- ---------------------------------------------------------------------------
CREATE TABLE edificios (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id             BIGINT           NOT NULL REFERENCES campanas (id),
  direccion_original     TEXT             NOT NULL,
  calle                  TEXT             NOT NULL,
  calle_norm             TEXT             NOT NULL,
  numero                 INTEGER,                      -- NULL en esquinas sin número
  direccion_norm         TEXT             NOT NULL,    -- "calle numero" o "calle esq otra", sin tildes
  lat                    DOUBLE PRECISION CHECK (lat BETWEEN -90 AND 90),
  lng                    DOUBLE PRECISION CHECK (lng BETWEEN -180 AND 180),
  geo_estado             TEXT             NOT NULL DEFAULT 'pendiente' CHECK (geo_estado IN ('pendiente', 'ok', 'aproximado', 'fallido', 'manual')),
  geo_display_name       TEXT             NOT NULL DEFAULT '',
  titular                TEXT             NOT NULL DEFAULT '',
  uso                    TEXT             NOT NULL DEFAULT '',
  observaciones          TEXT             NOT NULL DEFAULT '',
  estado_inspeccion      TEXT             NOT NULL DEFAULT 'pendiente' CHECK (estado_inspeccion IN ('pendiente', 'inspeccionado', 'observado', 'regularizado')),
  -- Datos de Catastro (cuando el edificio viene del cruce)
  padron                 TEXT             NOT NULL DEFAULT '',
  estado_obra            TEXT             NOT NULL DEFAULT '',
  calle_origen           TEXT             NOT NULL DEFAULT '',
  altura_original        TEXT             NOT NULL DEFAULT '',
  esquina                TEXT             NOT NULL DEFAULT '',
  conclusion_cruce       TEXT             NOT NULL DEFAULT '',
  misma_calle_otra_altura BOOLEAN         NOT NULL DEFAULT FALSE,
  en_listado_sin_cert    BOOLEAN          NOT NULL DEFAULT FALSE,
  -- Informe del Word de edificios sin final de obra
  informe                TEXT             NOT NULL DEFAULT '',
  informe_lote           TEXT             NOT NULL DEFAULT '',
  origen                 TEXT             NOT NULL DEFAULT 'manual' CHECK (origen IN ('excel', 'manual')),
  lote_importacion       TEXT,
  creado_por             BIGINT           REFERENCES usuarios (id) ON DELETE SET NULL,
  id_origen              TEXT,                         -- _id que tenía en MongoDB (también ordena la carpeta de fotos)
  creado_en              TIMESTAMPTZ      NOT NULL DEFAULT now(),
  actualizado_en         TIMESTAMPTZ      NOT NULL DEFAULT now(),
  CONSTRAINT edificios_direccion_uk UNIQUE (campana_id, direccion_norm),
  CONSTRAINT edificios_lat_lng_juntos CHECK ((lat IS NULL) = (lng IS NULL))
);
CREATE INDEX edificios_calle_norm_idx  ON edificios (calle_norm);
CREATE INDEX edificios_geo_estado_idx  ON edificios (geo_estado);
CREATE INDEX edificios_inspeccion_idx  ON edificios (estado_inspeccion);
CREATE INDEX edificios_lote_idx        ON edificios (lote_importacion) WHERE lote_importacion IS NOT NULL;
CREATE INDEX edificios_direccion_trgm  ON edificios USING gin (direccion_original gin_trgm_ops);

CREATE TABLE documentos_edificio (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edificio_id       BIGINT      NOT NULL REFERENCES edificios (id) ON DELETE CASCADE,
  tipo_id           BIGINT      NOT NULL REFERENCES tipos_documento (id),
  presente          BOOLEAN     NOT NULL DEFAULT FALSE,
  fecha_emision     DATE,
  fecha_vencimiento DATE,
  nro_referencia    TEXT        NOT NULL DEFAULT '',
  observaciones     TEXT        NOT NULL DEFAULT '',
  lote_importacion  TEXT,
  creado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT documentos_edificio_uk UNIQUE (edificio_id, tipo_id),
  CONSTRAINT documentos_fechas_ok CHECK (fecha_emision IS NULL OR fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_emision)
);
CREATE INDEX documentos_vencimiento_idx ON documentos_edificio (fecha_vencimiento) WHERE fecha_vencimiento IS NOT NULL;

-- Fotos: el archivo queda en disco (o en un almacenamiento de objetos) y aquí solo su ruta relativa.
CREATE TABLE fotos_edificio (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edificio_id      BIGINT      NOT NULL REFERENCES edificios (id) ON DELETE CASCADE,
  archivo          TEXT        NOT NULL,                -- nombre del archivo
  ruta             TEXT        NOT NULL,                -- ruta relativa a uploads/ ("edificios/<carpeta>/<archivo>")
  nombre_original  TEXT        NOT NULL DEFAULT '',
  tipo             TEXT        NOT NULL DEFAULT 'image/jpeg',
  tamano           INTEGER     NOT NULL DEFAULT 0 CHECK (tamano >= 0),
  orden            INTEGER     NOT NULL DEFAULT 0,
  descripcion      TEXT        NOT NULL DEFAULT '',
  lote_importacion TEXT,
  creado_por       BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
  creado_en        TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fotos_ruta_uk UNIQUE (ruta)
);
CREATE INDEX fotos_edificio_idx ON fotos_edificio (edificio_id, orden);

CREATE TABLE inspecciones (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edificio_id    BIGINT      NOT NULL REFERENCES edificios (id) ON DELETE CASCADE,
  fecha          DATE        NOT NULL,
  inspector_id   BIGINT      REFERENCES inspectores (id) ON DELETE SET NULL,
  resultado      TEXT        NOT NULL CHECK (resultado IN ('inspeccionado', 'observado', 'regularizado')),
  observaciones  TEXT        NOT NULL DEFAULT '',
  creado_por     BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX inspecciones_edificio_idx ON inspecciones (edificio_id, fecha DESC);

-- ---------------------------------------------------------------------------
-- Infracciones (actas) con sus pases
-- ---------------------------------------------------------------------------
CREATE TABLE infracciones (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_acta            TEXT        NOT NULL,
  edificio_id            BIGINT      NOT NULL REFERENCES edificios (id),
  infractor              TEXT        NOT NULL DEFAULT '',
  descripcion            TEXT        NOT NULL DEFAULT '',   -- motivo tal como figura en el acta
  normativa              TEXT        NOT NULL DEFAULT '',
  fecha_infraccion       DATE        NOT NULL,
  estado_id              BIGINT      NOT NULL REFERENCES estados (id),
  oficina_actual_id      BIGINT      NOT NULL REFERENCES oficinas (id),
  asignado_a             BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
  observaciones          BOOLEAN     NOT NULL DEFAULT FALSE,
  detalle_observaciones  TEXT        NOT NULL DEFAULT '',
  expediente_numero      TEXT        NOT NULL DEFAULT '',   -- con expediente la infracción queda cerrada
  expediente_fecha       DATE,
  expediente_generado_por BIGINT     REFERENCES usuarios (id) ON DELETE SET NULL,
  eliminado              BOOLEAN     NOT NULL DEFAULT FALSE, -- baja lógica
  motivo_eliminacion     TEXT        NOT NULL DEFAULT '',
  eliminado_por          BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
  origen                 TEXT        NOT NULL DEFAULT 'manual' CHECK (origen IN ('manual', 'excel')),
  lote_importacion       TEXT,
  creado_por             BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
  creado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT infracciones_acta_uk UNIQUE (numero_acta),
  CONSTRAINT infracciones_baja_con_motivo CHECK (NOT eliminado OR length(motivo_eliminacion) >= 3)
);
CREATE INDEX infracciones_edificio_idx ON infracciones (edificio_id);
CREATE INDEX infracciones_fecha_idx    ON infracciones (fecha_infraccion);
CREATE INDEX infracciones_estado_idx   ON infracciones (estado_id, oficina_actual_id);
CREATE INDEX infracciones_activas_idx  ON infracciones (edificio_id) WHERE NOT eliminado;
CREATE INDEX infracciones_lote_idx     ON infracciones (lote_importacion) WHERE lote_importacion IS NOT NULL;
CREATE INDEX infracciones_infractor_trgm ON infracciones USING gin (infractor gin_trgm_ops);

CREATE TABLE infraccion_inspectores (
  infraccion_id BIGINT NOT NULL REFERENCES infracciones (id) ON DELETE CASCADE,
  inspector_id  BIGINT NOT NULL REFERENCES inspectores (id),
  PRIMARY KEY (infraccion_id, inspector_id)
);
CREATE INDEX infraccion_inspectores_inspector_idx ON infraccion_inspectores (inspector_id);

CREATE TABLE infraccion_motivos (
  infraccion_id BIGINT NOT NULL REFERENCES infracciones (id) ON DELETE CASCADE,
  motivo_id     BIGINT NOT NULL REFERENCES motivos_infraccion (id),
  PRIMARY KEY (infraccion_id, motivo_id)
);
CREATE INDEX infraccion_motivos_motivo_idx ON infraccion_motivos (motivo_id);

-- Historial de pases entre oficinas, en orden.
CREATE TABLE infraccion_movimientos (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  infraccion_id      BIGINT      NOT NULL REFERENCES infracciones (id) ON DELETE CASCADE,
  orden              INTEGER     NOT NULL,
  fecha              TIMESTAMPTZ NOT NULL DEFAULT now(),
  oficina_origen_id  BIGINT      REFERENCES oficinas (id),
  oficina_destino_id BIGINT      NOT NULL REFERENCES oficinas (id),
  estado_id          BIGINT      REFERENCES estados (id),
  por_usuario_id     BIGINT      NOT NULL REFERENCES usuarios (id),
  comentarios        TEXT        NOT NULL DEFAULT '',
  CONSTRAINT movimientos_orden_uk UNIQUE (infraccion_id, orden)
);

-- ---------------------------------------------------------------------------
-- Edificios notificados y sus plazos
-- ---------------------------------------------------------------------------
CREATE TABLE notificaciones (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edificio_id          BIGINT      NOT NULL REFERENCES edificios (id) ON DELETE CASCADE,
  fecha_notificacion   DATE        NOT NULL,
  plazo_dias           INTEGER     CHECK (plazo_dias BETWEEN 1 AND 3650),  -- NULL: notificado sin plazo registrado
  fecha_vencimiento    DATE,                                              -- vigente, con prórrogas
  vencimiento_original DATE,                                              -- antes de las prórrogas
  plazo_original       TEXT        NOT NULL DEFAULT '',                   -- tal como figura en la planilla ("72 hs vence 9/10/26")
  prorroga             BOOLEAN     NOT NULL DEFAULT FALSE,
  resultado            TEXT        NOT NULL DEFAULT '' CHECK (resultado IN ('', 'presento', 'acta')), -- presentó documentación / pasó a acta
  boleta               TEXT        NOT NULL DEFAULT '',
  razon_social         TEXT        NOT NULL DEFAULT '',
  inspector            TEXT        NOT NULL DEFAULT '',
  observaciones        TEXT        NOT NULL DEFAULT '',                   -- última novedad
  origen               TEXT        NOT NULL DEFAULT 'manual' CHECK (origen IN ('excel', 'manual')),
  lote_importacion     TEXT,
  creado_por           BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
  creado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT notificaciones_vencimiento_ok CHECK (fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_notificacion)
);
CREATE INDEX notificaciones_edificio_idx     ON notificaciones (edificio_id, fecha_notificacion DESC);
CREATE INDEX notificaciones_vencimiento_idx  ON notificaciones (fecha_vencimiento) WHERE fecha_vencimiento IS NOT NULL;
CREATE INDEX notificaciones_boleta_idx       ON notificaciones (boleta) WHERE boleta <> '';
CREATE INDEX notificaciones_lote_idx         ON notificaciones (lote_importacion) WHERE lote_importacion IS NOT NULL;

