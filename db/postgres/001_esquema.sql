CREATE INDEX auditoria_entidad_idx ON auditoria (entidad, entidad_id);
CREATE INDEX auditoria_fecha_idx   ON auditoria (creado_en DESC);

-- ---------------------------------------------------------------------------
-- Triggers de actualizado_en
-- ---------------------------------------------------------------------------
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'usuarios', 'campanas', 'inspectores', 'motivos_infraccion', 'estados', 'oficinas', 'tipos_documento',
    'edificios', 'documentos_edificio', 'fotos_edificio', 'inspecciones', 'infracciones', 'notificaciones', 'geo_cache'
  ] LOOP
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION tocar_actualizado_en()', t || '_actualizado', t);
  END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- Vistas de consulta
-- ---------------------------------------------------------------------------
-- Estado de plazo de la notificación vigente (la más reciente) de cada edificio.
-- Misma regla que la aplicación: por vencer = faltan 10 días o menos; el día del vencimiento todavía está en plazo.
CREATE VIEW v_notificacion_vigente AS
SELECT DISTINCT ON (n.edificio_id)
       n.*,
       (n.fecha_vencimiento - CURRENT_DATE) AS dias_restantes,
       CASE
         WHEN n.resultado = 'presento'           THEN 'presento'
         WHEN n.resultado = 'acta'               THEN 'acta'
         WHEN n.fecha_vencimiento IS NULL        THEN 'sin_plazo'
         WHEN n.fecha_vencimiento < CURRENT_DATE THEN 'vencido'
         WHEN n.fecha_vencimiento - CURRENT_DATE <= 10 THEN 'por_vencer'
         ELSE 'en_plazo'
       END AS estado_plazo
  FROM notificaciones n
 ORDER BY n.edificio_id, n.fecha_notificacion DESC, n.id DESC;

-- Una fila por edificio con sus conteos.
CREATE VIEW v_edificios_resumen AS
SELECT e.*,
       (SELECT count(*) FROM infracciones i WHERE i.edificio_id = e.id AND NOT i.eliminado) AS actas,
       (SELECT count(*) FROM fotos_edificio f WHERE f.edificio_id = e.id)                   AS fotos,
       (SELECT count(*) FROM notificaciones n WHERE n.edificio_id = e.id)                   AS notificaciones,
       (SELECT count(*) FROM documentos_edificio d WHERE d.edificio_id = e.id AND d.presente) AS documentos_presentes
  FROM edificios e;

COMMIT;
