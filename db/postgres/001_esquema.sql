CREATE TABLE auditoria (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  accion     TEXT        NOT NULL,
  entidad    TEXT        NOT NULL,
  entidad_id TEXT,
  usuario_id BIGINT      REFERENCES usuarios (id) ON DELETE SET NULL,
